    // ==========================================
    // PDF Helper Methods
    // ==========================================
    private Document createPdfDocument(ByteArrayOutputStream out, String title, int tableColumns, List<String> headers, PdfTableDataFiller filler) {
        Document document = new Document(PageSize.A4);
        try {
            PdfWriter.getInstance(document, out);
            document.open();

            // Header/Logo section
            Font companyFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, java.awt.Color.DARK_GRAY);
            Paragraph companyPara = new Paragraph("ERASM ENTERPRISE SYSTEM", companyFont);
            companyPara.setAlignment(Element.ALIGN_CENTER);
            document.add(companyPara);

            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14, java.awt.Color.BLUE);
            Paragraph titlePara = new Paragraph(title, titleFont);
            titlePara.setAlignment(Element.ALIGN_CENTER);
            titlePara.setSpacingAfter(20);
            document.add(titlePara);

            // Metadata section
            Font metaFont = FontFactory.getFont(FontFactory.HELVETICA, 10, java.awt.Color.BLACK);
            Paragraph metaPara = new Paragraph("Generated Date: " + LocalDateTime.now().format(formatter) + " | Generated By: ERASM Admin", metaFont);
            metaPara.setSpacingAfter(15);
            document.add(metaPara);

            // Table Creation
            PdfPTable table = new PdfPTable(tableColumns);
            table.setWidthPercentage(100f);

            Font headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, java.awt.Color.WHITE);
            for (String header : headers) {
                PdfPCell cell = new PdfPCell(new Paragraph(header, headerFont));
                cell.setBackgroundColor(java.awt.Color.BLUE);
                cell.setPadding(6);
                cell.setHorizontalAlignment(Element.ALIGN_CENTER);
                table.addCell(cell);
            }

            filler.fillTable(table);
            document.add(table);

            // Footer
            Paragraph footer = new Paragraph("\nPage 1 of 1 — Confidential — Generated by ERASM Reports Engine", FontFactory.getFont(FontFactory.HELVETICA, 8, java.awt.Color.GRAY));
            footer.setAlignment(Element.ALIGN_CENTER);
            document.add(footer);

            document.close();
        } catch (Exception e) {
            logger.error("Error generating PDF: " + e.getMessage(), e);
            throw new ReportGenerationException("Error generating PDF report: " + e.getMessage());
        }
        return document;
    }

    interface PdfTableDataFiller {
        void fillTable(PdfPTable table);
    }

