    @Override
    @Transactional(readOnly = true)
    public byte[] exportProjectsPdf() {
        logger.info("Exporting projects allocation report to PDF");
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        List<AllocationResponse> allocations = reportService.getProjectAllocationReport();
        List<String> headers = List.of("ID", "Project Name", "Employee Name", "Allocation %", "Start Date", "End Date", "Status");

        createPdfDocument(out, "Project Allocations Report", 7, headers, table -> {
            Font cellFont = FontFactory.getFont(FontFactory.HELVETICA, 9);
            for (AllocationResponse alloc : allocations) {
                table.addCell(new PdfPCell(new Paragraph(alloc.getAllocationId() != null ? alloc.getAllocationId().toString() : "", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getProjectName() != null ? alloc.getProjectName() : "", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getEmployeeName() != null ? alloc.getEmployeeName() : "", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getAllocationPercentage() != null ? alloc.getAllocationPercentage().toString() + "%" : "0%", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getStartDate() != null ? alloc.getStartDate().toString() : "", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getEndDate() != null ? alloc.getEndDate().toString() : "-", cellFont)));
                table.addCell(new PdfPCell(new Paragraph(alloc.getStatus() != null ? alloc.getStatus().toString() : "", cellFont)));
            }
        });
        return out.toByteArray();
    }

