    // ==========================================
    // Excel Helpers & Implementation
    // ==========================================
    private byte[] generateExcel(String sheetName, List<String> headers, ExcelDataFiller filler) {
        try (Workbook workbook = new XSSFWorkbook(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Sheet sheet = workbook.createSheet(sheetName);

            // Styling Header
            CellStyle headerStyle = workbook.createCellStyle();
            org.apache.poi.ss.usermodel.Font headerFont = workbook.createFont();
            headerFont.setBold(true);
            headerStyle.setFont(headerFont);

            Row headerRow = sheet.createRow(0);
            for (int i = 0; i < headers.size(); i++) {
                Cell cell = headerRow.createCell(i);
                cell.setCellValue(headers.get(i));
                cell.setCellStyle(headerStyle);
            }

            filler.fillExcel(sheet, workbook);

            // Auto-size columns
            for (int i = 0; i < headers.size(); i++) {
                sheet.autoSizeColumn(i);
            }

            workbook.write(out);
            return out.toByteArray();
        } catch (Exception e) {
            logger.error("Error generating Excel report: " + e.getMessage(), e);
            throw new ReportGenerationException("Error generating Excel report: " + e.getMessage());
        }
    }

    interface ExcelDataFiller {
        void fillExcel(Sheet sheet, Workbook workbook);
    }

